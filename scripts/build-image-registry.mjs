import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = process.cwd();
const DIR = path.join(ROOT, 'assets', 'recipes');
const TARGET = path.join(ROOT, 'src', 'assets', 'recipeImages.ts');

async function main() {
  let files = [];
  try {
    files = (await fs.readdir(DIR)).filter((file) => file.endsWith('.jpg'));
  } catch {
    files = [];
  }
  files.sort();

  const lines = files.map((file) => {
    const key = file.replace(/\.jpg$/, '');
    return `  '${key}': require('../../assets/recipes/${file}'),`;
  });

  const content = `import type { ImageSourcePropType } from 'react-native';

/**
 * Bundle registry for recipe photography.
 *
 * Generated by \`node scripts/build-image-registry.mjs\` from assets/recipes so a
 * recipe can never point at a missing asset.
 */
export const RECIPE_IMAGES: Record<string, ImageSourcePropType> = {
${lines.join('\n')}
};

export function getRecipeImage(
  imageKey: string | undefined,
  remoteUrl?: string,
): ImageSourcePropType | null {
  if (imageKey && RECIPE_IMAGES[imageKey]) return RECIPE_IMAGES[imageKey];
  if (remoteUrl) return { uri: remoteUrl };
  return null;
}

export const HAS_BUNDLED_IMAGES = Object.keys(RECIPE_IMAGES).length > 0;
export const BUNDLED_IMAGE_COUNT = Object.keys(RECIPE_IMAGES).length;
`;

  await fs.writeFile(TARGET, content, 'utf8');
  console.log(`registry written with ${files.length} images`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
